const fs=require('node:fs');
const path=require('node:path');
const {spawn}=require('node:child_process');
const root=path.resolve(__dirname,'..');
const windows=process.platform==='win32';
const runtime=process.platform==='linux'?'runtime-linux':'runtime';
const frozen=path.join(root,'.desktop-build',runtime,'shas-backend',windows?'shas-backend.exe':'shas-backend');
const python=path.join(root,'.venv',windows?'Scripts/python.exe':'bin/python');
const corpus=process.env.SHAS_CORPUS||path.join(root,'data/prepared');
const frontend=process.env.SHAS_FRONTEND||path.join(root,'dist');
if(!fs.existsSync(path.join(corpus,'manifest.json')))throw Error('Prepared Shas content is missing. Set SHAS_CORPUS to its folder.');
if(!fs.existsSync(path.join(frontend,'index.html')))throw Error('Build the interface with npm run build first.');
const executable=fs.existsSync(frozen)?frozen:python;
if(!fs.existsSync(executable))throw Error('Reader runtime is missing. Install the Python runtime dependencies on the server.');
const args=executable===frozen?[]:['-m','desktop.backend'];
args.push('--configuration','Release');
const child=spawn(executable,args,{cwd:root,stdio:'inherit',env:{...process.env,NODE_ENV:'production',SHAS_CORPUS:corpus,SHAS_FRONTEND:frontend}});
child.once('error',error=>{console.error(error.message);process.exitCode=1});
child.once('exit',code=>{process.exitCode=code??1});
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,()=>child.kill(signal));
